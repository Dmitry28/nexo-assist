import { ruDate } from '../ru-date';

describe('ruDate', () => {
  it.each([
    ['Извещение о проведении 30.06.2025 аукциона', '30.06.2025'],
    ['Извещение о проведении 5 ноября 2026 г.', '05.11.2026'],
    ['АУКЦИОН 27 ИЮНЯ 2025 Г.', '27.06.2025'],
    ['без даты', undefined],
    ['5 ноября 2026 г. (решение от 12.09.2026)', '05.11.2026'],
    ['99.99.2025 — не дата', undefined],
  ])('%p → %p', (text, expected) => {
    expect(ruDate(text)).toBe(expected);
  });
});
